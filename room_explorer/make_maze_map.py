#!/usr/bin/env python3
"""
make_maze_map.py
----------------------------------------------------------
사용자 치수 도면(2026-08-05 이미지)대로 maze_195x162_fix.pgm 을 생성한다.

이미지에 적힌 치수 (m):
  외곽 1.95 x 1.62, 벽 두께 0.05, 벽돌 모듈 0.19 x 0.05
  이빨(콤) 간격: 왼벽 안쪽에서 0.4 | 0.425 | 0.425  -> 이빨 x 0.45/0.925/1.40 (+0.05)
  이빨 길이 0.38(=0.19x2), 끝 발(foot)은 이빨 중심 ±0.095 (0.19 폭)
  가운데 가로 바: 위/아래 벽에서 각각 0.735 떨어짐 (y 0.785~0.835)
  오른쪽 세로 바: 바깥 위/아래에서 0.38 (y 0.38~1.24), x 1.90~1.95
    바 양 끝의 왼쪽 훅: 가로 0.095 (x 1.855~1.95)
  오른쪽 구석 스터브: 길이 0.095 (y 0.05~0.145 / 1.475~1.57)
  왼벽 입구 스터브: 발 높이에서 x 0~0.15 (기존 실측 유지 — 도면 무라벨)

실행:  python3 make_maze_map.py 출력.pgm
       (해상도 0.005 m, 390x324, 흰 254=자유 / 검정 0=벽)
----------------------------------------------------------
"""
import sys

import numpy as np

RES = 0.005
W, H = 390, 324          # 1.95 x 1.62 m

# (x0, x1, y0, y1) — 월드 좌표[m], 원점 왼쪽 아래, y 위로
RECTS = [
    (0.000, 1.950, 0.000, 0.050),      # 아래 벽
    (0.000, 1.950, 1.570, 1.620),      # 위 벽
    (0.000, 0.050, 0.000, 1.620),      # 왼 벽
    (1.900, 1.950, 0.050, 0.145),      # 오른쪽 아래 구석 스터브 (0.095)
    (1.900, 1.950, 1.475, 1.570),      # 오른쪽 위 구석 스터브 (0.095)
    (1.900, 1.950, 0.380, 1.240),      # 오른쪽 세로 바
    (1.855, 1.950, 0.380, 0.430),      # 바 아래 훅 (가로 0.095)
    (1.855, 1.950, 1.190, 1.240),      # 바 위 훅 (가로 0.095)
    (0.380, 1.525, 0.785, 0.835),      # 가운데 가로 바 (0.735 간격)
    (0.000, 0.150, 0.430, 0.480),      # 왼벽 아래 입구 스터브
    (0.000, 0.150, 1.140, 1.190),      # 왼벽 위 입구 스터브
]
for cx in (0.475, 0.950, 1.425):       # 이빨 중심 (간격 0.4/0.425/0.425)
    RECTS += [
        (cx - 0.025, cx + 0.025, 0.050, 0.480),   # 아래 이빨 (길이 0.38+발)
        (cx - 0.095, cx + 0.095, 0.430, 0.480),   # 아래 발 (0.19 폭)
        (cx - 0.025, cx + 0.025, 1.140, 1.570),   # 위 이빨
        (cx - 0.095, cx + 0.095, 1.140, 1.190),   # 위 발
    ]


def build():
    img = np.full((H, W), 254, np.uint8)          # 자유공간
    for x0, x1, y0, y1 in RECTS:
        c0, c1 = int(round(x0 / RES)), int(round(x1 / RES))
        r0, r1 = int(round(y0 / RES)), int(round(y1 / RES))
        # PGM 은 row 0 = 위쪽. 월드 y -> 이미지 행으로 뒤집는다.
        img[H - r1:H - r0, c0:c1] = 0
    return img


def save_pgm(path, img):
    with open(path, "wb") as f:
        f.write(b"P5\n%d %d\n255\n" % (img.shape[1], img.shape[0]))
        f.write(img.tobytes())


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "maze_195x162_fix.pgm"
    save_pgm(out, build())
    print("저장: %s (%dx%d @ %.3f m)" % (out, W, H, RES))
